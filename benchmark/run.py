from __future__ import annotations

import argparse
import json
from pathlib import Path

from benchmark.scenarios import run_case, run_mixed_case

CASES = (
    ("identical_loop", {"calls": 20, "tool_cost": 0.01, "budget": 0.025, "official_limit": 2}),
    ("expensive_tool_spike", {"calls": 10, "tool_cost": 0.20, "budget": 0.50, "official_limit": 2}),
    ("short_loop", {"calls": 5, "tool_cost": 0.01, "budget": 0.025, "official_limit": 2}),
)
BASELINES = ("none", "official", "full")


def main() -> int:
    parser = argparse.ArgumentParser(prog="benchmark")
    parser.add_argument("--out", default="reports")
    args = parser.parse_args()

    results = []
    for scenario, kwargs in CASES:
        for baseline in BASELINES:
            results.append(run_case(scenario, baseline, **kwargs).to_dict())
    # Heterogeneous-cost scenario: a call-count limit of 10 allows the whole
    # script even though two calls are 200x more expensive than the others.
    # The USD-aware full guard should stop within the budget.
    for baseline in BASELINES:
        results.append(run_mixed_case(baseline).to_dict())

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "benchmark.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    lines = [
        "# resguard mechanics benchmark",
        "",
        "> Scripted model + mock tools. These numbers are generated by the harness;",
        "> they measure guard mechanics, not production quality or task success.",
        "",
        "| Scenario | Baseline | Executed / attempted tool calls | Declared USD | Budget USD | Within budget | Termination | Elapsed ms |",
        "|---|---|---:|---:|---:|---|---|---:|",
    ]
    for item in results:
        lines.append(
            f"| {item['scenario']} | {item['baseline']} | "
            f"{item['executed_tool_calls']} / {item['attempted_tool_calls']} | "
            f"{item['declared_usd']:.3f} | {item['budget_usd']:.3f} | "
            f"{'yes' if item['within_budget'] else 'NO'} | "
            f"{item['termination']} | {item['elapsed_ms']:.2f} |"
        )
    (out / "benchmark.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {out / 'benchmark.json'} and {out / 'benchmark.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
